import { test, expect, type Page } from '@playwright/test'

async function setup(page: Page, ordinary = false, readOnly = false) {
  const requests: { path: string; method: string }[] = []
  await page.context().addCookies([{ name: 'Admin-Token', value: 'storage-preview-test', url: String(test.info().project.use.baseURL) }])
  await page.route('**/dev-api/**', async route => {
    const path = new URL(route.request().url()).pathname.replace('/dev-api', '')
    requests.push({ path, method: route.request().method() })
    const permissions = readOnly ? ['metal:warehouse:list'] : ['metal:warehouse:list', 'metal:warehouse:add', 'metal:warehouse:edit', 'metal:warehouse:remove', 'metal:inventory:list', 'metal:warehouse-order:list', 'metal:work-order:list', 'metal:quotation:list']
    const data = path === '/getInfo' ? { code: 200, user: { userId: ordinary ? 2 : 1, factoryId: ordinary ? '7' : null, userName: 'preview-user', nickName: '预览人员' }, roles: ['staff'], permissions } : { code: 200, data: [], rows: [], total: 0 }
    await route.fulfill({ json: data })
  })
  await page.goto('/metal/storage-warehouses')
  await expect(page.getByText('前端预览', { exact: true })).toBeVisible()
  if (!ordinary) {
    await page.getByRole('combobox', { name: '所属工厂', exact: true }).press('ArrowDown')
    await page.getByRole('option', { name: '演示工厂一', exact: true }).click()
  }
  await expect(page.getByRole('cell', { name: '原料库', exact: true })).toBeVisible()
  return requests
}

test('warehouse navigation and local CRUD, filters, reference protection never call business APIs', async ({ page }) => {
  const requests = await setup(page)
  const groups = await page.locator('.nav-group').allTextContents()
  expect(groups.join('|')).toMatch(/报价管理.*工单管理.*仓储管理/)
  const nav = page.getByRole('navigation', { name: '主导航' })
  const links = await nav.getByRole('link').allTextContents()
  expect(links.indexOf('仓储工单管理')).toBeLessThan(links.indexOf('仓库管理'))
  expect(links.indexOf('仓储管理')).toBeLessThan(links.indexOf('仓储工单管理'))
  await page.getByRole('button', { name: '添加', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '添加仓库', exact: true })
  await dialog.getByRole('button', { name: '确认', exact: true }).click()
  await expect(dialog.getByText('请输入仓库名称', { exact: true })).toBeVisible()
  await dialog.getByRole('textbox', { name: '仓库名称', exact: true }).fill('原料库')
  await dialog.getByRole('button', { name: '确认', exact: true }).click()
  await expect(dialog.getByText('本厂已存在同名仓库', { exact: true })).toBeVisible()
  await dialog.getByRole('textbox', { name: '仓库名称', exact: true }).fill(' 临时仓库 ')
  await dialog.getByRole('button', { name: '确认', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await page.getByRole('textbox', { name: '仓库名称筛选', exact: true }).fill('临时')
  await page.getByRole('button', { name: '查询', exact: true }).click()
  await expect(page.getByRole('cell', { name: '原料库', exact: true })).toHaveCount(0)
  await page.getByRole('row').filter({ hasText: '临时仓库' }).getByRole('button', { name: '编辑', exact: true }).click()
  const editor = page.getByRole('dialog', { name: '编辑仓库', exact: true })
  await editor.getByRole('textbox', { name: '仓库名称', exact: true }).fill('临时仓库二')
  await editor.getByText('停用', { exact: true }).click()
  await editor.getByRole('button', { name: '确认', exact: true }).click()
  const row = page.getByRole('row').filter({ hasText: '临时仓库二' })
  await expect(row).toContainText('停用')
  await page.getByRole('button', { name: '重置', exact: true }).click()
  await row.getByRole('checkbox').press('Space')
  await page.getByRole('row').filter({ hasText: '原料库' }).getByRole('checkbox').press('Space')
  await page.locator('.storage-filter').getByRole('button', { name: '删除', exact: true }).click()
  await page.getByRole('dialog', { name: '删除仓库', exact: true }).getByRole('button', { name: '删除', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '删除仓库', exact: true })).not.toBeVisible()
  await expect(row).toBeVisible()
  await expect(page.getByRole('row').filter({ hasText: '原料库' })).toBeVisible()
  await row.getByRole('button', { name: '删除', exact: true }).click()
  await page.getByRole('dialog', { name: '删除仓库', exact: true }).getByRole('button', { name: '删除', exact: true }).click()
  await expect(row).toHaveCount(0)
  await page.getByRole('button', { name: '重置', exact: true }).click()
  await expect(page.getByRole('textbox', { name: '仓库名称筛选', exact: true })).toHaveValue('')
  const original = page.getByRole('row').filter({ hasText: '原料库' })
  await original.getByRole('button', { name: '删除', exact: true }).click()
  await page.getByRole('dialog', { name: '删除仓库', exact: true }).getByRole('button', { name: '删除', exact: true }).click()
  await expect(page.getByText('所选仓库已被库存或仓储工单引用，不能删除；本次未删除任何仓库', { exact: true }).last()).toBeVisible()
  await expect(original).toBeVisible()
  expect(requests.filter(r => r.path.startsWith('/metal/') || r.method !== 'GET')).toEqual([])
})

test('warehouse dirty form confirms close and route leave, and factory switch clears filters', async ({ page }) => {
  await setup(page)
  await page.getByRole('textbox', { name: '仓库名称筛选', exact: true }).fill('原料')
  await page.getByRole('button', { name: '查询', exact: true }).click()
  await page.getByRole('combobox', { name: '所属工厂', exact: true }).press('ArrowDown')
  await page.getByRole('option', { name: '演示工厂二', exact: true }).click()
  await expect(page.getByRole('textbox', { name: '仓库名称筛选', exact: true })).toHaveValue('')
  await page.getByRole('button', { name: '添加', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '添加仓库', exact: true })
  await dialog.getByRole('textbox', { name: '仓库名称', exact: true }).fill('未保存仓库')
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await page.getByRole('button', { name: '继续填写', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '确认离开', exact: true })).not.toBeVisible()
  await expect(dialog.getByRole('textbox', { name: '仓库名称', exact: true })).toHaveValue('未保存仓库')
  await page.locator('nav a[href="/metal/storage-inventory"]').dispatchEvent('click')
  await expect(page.getByText('放弃未保存的仓库资料？', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '继续填写', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '确认离开', exact: true })).not.toBeVisible()
  await expect(page).toHaveURL(/storage-warehouses/)
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await page.getByRole('button', { name: '放弃', exact: true }).click()
  await expect(dialog).not.toBeVisible()
})

test('ordinary warehouse account is fixed to its factory and read-only permission hides mutations', async ({ page }) => {
  const requests = await setup(page, true, true)
  await expect(page.getByRole('combobox', { name: '所属工厂', exact: true })).toBeDisabled()
  await expect(page.getByRole('cell', { name: '所属工厂（演示）', exact: true })).toHaveCount(2)
  for (const name of ['添加', '编辑', '删除']) await expect(page.getByRole('button', { name, exact: true })).toHaveCount(0)
  expect(requests.filter(r => r.path.startsWith('/metal/') || r.method !== 'GET')).toEqual([])
})
